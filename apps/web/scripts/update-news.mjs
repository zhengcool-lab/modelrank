#!/usr/bin/env node
/**
 * update-news.mjs — 把 data-pipeline 抓到的真实新闻写入前端数据文件。
 *
 * 用法（仓库根目录下）：
 *   cd apps/web && node scripts/update-news.mjs
 *
 * 输入：data-pipeline/out/news.json（pipeline run --dry-run 产出，is_mock=false 才用）
 * 输出：apps/web/src/lib/news-data.ts（导出 UI_NEWS: UINewsItem[]，供各页面构建时使用）
 *
 * 纪律：管道全部失败回退 mock 时（is_mock=true）不覆盖，保留上次真实数据。
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const OUT_JSON = fileURLToPath(new URL("../../../data-pipeline/out/news.json", import.meta.url));
const OUT_TS = fileURLToPath(new URL("../src/lib/news-data.ts", import.meta.url));

const VALID_CATS = new Set(["发布", "评测", "融资", "政策", "价格"]);

let raw;
try {
  raw = JSON.parse(readFileSync(OUT_JSON, "utf8"));
} catch (e) {
  console.error(`[update-news] 无法读取 ${OUT_JSON}: ${e.message}`);
  process.exit(1);
}

let list = [];
let isMock = false;
let source = "news";

if (Array.isArray(raw)) {
  // 兼容：out/news.json 顶层即新闻数组
  list = raw;
  isMock = false;
  source = "news";
} else {
  list = raw.news || [];
  isMock = !!raw.is_mock;
  source = raw.source ?? "news";
}
if (isMock) {
  console.log("[update-news] 管道回退 mock，跳过覆盖，保留现有 news-data.ts");
  process.exit(0);
}

const items = list
  .filter((n) => n && typeof n.title === "string" && n.title.trim())
  .map((n, i) => ({
    id: n.id && String(n.id).startsWith("n-") ? String(n.id) : `n-auto-${i + 1}`,
    category: VALID_CATS.has(n.category) ? n.category : "发布",
    title: n.title.trim(),
    summary: (n.summary || "").trim(),
    source: (n.source || "AI 行业").trim(),
    time: n.time || new Date().toISOString(),
    ...(n.related_model ? { relatedModel: n.related_model } : {}),
    url: n.url || "",
  }))
  .sort((a, b) => new Date(b.time).getTime() - new Date(a.time).getTime())
  .slice(0, 30);

const banner = `// AUTO-GENERATED by apps/web/scripts/update-news.mjs — 每日由 data-pipeline 真实抓取生成，勿手改。
// 生成时间：${new Date().toISOString()}；条目数：${items.length}；数据源：${source}
import type { UINewsItem } from "./types";

export const UI_NEWS: UINewsItem[] = ${JSON.stringify(items, null, 2)};
`;

writeFileSync(OUT_TS, banner, "utf8");
console.log(`[update-news] 已写入 ${OUT_TS}（${items.length} 条，mock=${isMock}）`);
